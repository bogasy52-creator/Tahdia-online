self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE_NAME).then((cache) => cache.addAll(APP_SHELL)));
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) => Promise.all(keys.filter((key) => ![CACHE_NAME,MEDIA_CACHE].includes(key)).map((key) => caches.delete(key)))).then(()=>self.clients.claim())
  );
});

self.addEventListener('fetch', (event) => {
  if (event.request.method !== 'GET') return;
  const url = new URL(event.request.url);
  if (url.origin === self.location.origin && (url.pathname.startsWith('/assets/quiz_photos/') || url.pathname.startsWith('/assets/sounds_pro/'))) {
    event.respondWith(caches.open(MEDIA_CACHE).then(async (cache) => { const cached=await cache.match(event.request); if(cached)return cached; const response=await fetch(event.request); if(response?.ok)cache.put(event.request,response.clone()).catch(()=>{}); return response; }));
    return;
  }
  if (url.origin !== self.location.origin || url.pathname.startsWith('/api/')) return;

  if (event.request.mode === 'navigate') {
    event.respondWith(fetch(event.request).then(async response => {
      if(response.ok){const cache=await caches.open(CACHE_NAME);await cache.put(event.request,response.clone())}
      return response;
    }).catch(async()=>await caches.match(event.request)||await caches.match(url.pathname.replace(/\/$/,'')+'.html')||await caches.match('/index.html')));
    return;
  }
  event.respondWith(
    caches.match(event.request).then((cached) => cached || fetch(event.request).then((response) => {
      if (!response || response.status !== 200 || response.type === 'opaque') return response;
      const copy = response.clone();
      caches.open(CACHE_NAME).then((cache) => cache.put(event.request, copy)).catch(() => {});
      return response;
    }).catch(() => {
      if (event.request.mode === 'navigate') return caches.match('/');
      return Response.error();
    }))
  );
});
