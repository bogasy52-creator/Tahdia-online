import { CATEGORIES } from '../src/questions.js';
import { writeFile } from 'node:fs/promises';
const banner='/* AUTO-GENERATED by scripts/sync-quiz-data.mjs — do not edit directly */\n';
// Keep sound questions self-describing.  The answer is tied to the actual
// basename of the shipped WAV file so a stale/renamed label can never drift
// away from the clip that the player hears.
const normalized = CATEGORIES.map((category) => category.id === 'sounds'
  ? {
      ...category,
      questions: category.questions.map((question) => {
        const soundKey = String(question.src || '').split('/').pop().replace(/\.wav$/i, '');
        return { ...question, soundKey, audioLabel: question.a };
      }),
    }
  : category);
await writeFile(new URL('../public/assets/js/questions-data.js', import.meta.url), banner+'window.BS_QUIZ_CATEGORIES='+JSON.stringify(normalized)+';\n');
console.log(`Synced ${normalized.length} categories / ${normalized.reduce((n,c)=>n+c.questions.length,0)} challenges`);
