import { CATEGORIES } from '../src/questions.js';
import { writeFile } from 'node:fs/promises';
const banner='/* AUTO-GENERATED by scripts/sync-quiz-data.mjs — do not edit directly */\n';
await writeFile(new URL('../public/assets/js/questions-data.js', import.meta.url), banner+'window.BS_QUIZ_CATEGORIES='+JSON.stringify(CATEGORIES)+';\n');
await writeFile(new URL('../public/assets/quiz-catalog.json',import.meta.url),JSON.stringify(CATEGORIES.map(({id,name,icon,desc,questions})=>({id,name,icon,desc,count:questions.length})))+'\n');
console.log(`Synced ${CATEGORIES.length} categories / ${CATEGORIES.reduce((n,c)=>n+c.questions.length,0)} challenges`);
